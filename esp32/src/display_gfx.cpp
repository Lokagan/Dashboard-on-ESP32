// ---- API LOCALES ----

// ⚠️ Buffer stocké dans l'ORDRE DE LA DALLE (octet fort d'abord), qui est aussi
// le LV_COLOR_FORMAT_RGB565_SWAPPED de LVGL — d'où le memcpy direct de SysInfo
// vers son lv_canvas. Les appelants manipulent du RGB565 normal (0xF800 = rouge).
static inline uint16_t wire(uint16_t c) { return (uint16_t)((c >> 8) | (c << 8)); }

// Intersection du rectangle demandé avec la surface. Retourne false si tout est
// hors champ — seul point où le clipping est fait, les primitives en dépendent.
static bool clip(const Canvas& c, int& x, int& y, int& w, int& h) {
    if (!c.px || w <= 0 || h <= 0) return false;
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > c.w) w = c.w - x;
    if (y + h > c.h) h = c.h - y;
    return (w > 0 && h > 0);
}

// ---- API PUBLIQUES ----

void fill(const Canvas& c, uint16_t color) {
    fill_rect(c, 0, 0, c.w, c.h, color);
}

void fill_rect(const Canvas& c, int x, int y, int w, int h, uint16_t color) {
    if (!clip(c, x, y, w, h)) return;
    const uint16_t v = wire(color);
    for (int row = 0; row < h; row++) {
        uint16_t* p = c.px + (size_t)(y + row) * c.w + x;
        for (int col = 0; col < w; col++) *p++ = v;
    }
}

void rect(const Canvas& c, int x, int y, int w, int h, uint16_t color) {
    if (w <= 0 || h <= 0) return;
    hline(c, x, y, w, color);
    hline(c, x, y + h - 1, w, color);
    vline(c, x, y, h, color);
    vline(c, x + w - 1, y, h, color);
}

void hline(const Canvas& c, int x, int y, int w, uint16_t color) {
    fill_rect(c, x, y, w, 1, color);
}

void vline(const Canvas& c, int x, int y, int h, uint16_t color) {
    fill_rect(c, x, y, 1, h, color);
}

void pixel(const Canvas& c, int x, int y, uint16_t color) {
    if (!c.px || x < 0 || y < 0 || x >= c.w || y >= c.h) return;
    c.px[(size_t)y * c.w + x] = wire(color);
}

void ring(const Canvas& c, int cx, int cy, int r_out, int r_in,
          float frac, uint16_t fg, uint16_t bg) {
    if (!c.px || r_out <= r_in || r_in < 0) return;
    if (frac < 0.0f) frac = 0.0f;
    if (frac > 1.0f) frac = 1.0f;

    const float sweep = frac * 6.283185f;
    const int   ro2 = r_out * r_out, ri2 = r_in * r_in;

    for (int y = cy - r_out; y <= cy + r_out; y++) {
        if (y < 0 || y >= c.h) continue;
        for (int x = cx - r_out; x <= cx + r_out; x++) {
            if (x < 0 || x >= c.w) continue;
            const int dx = x - cx, dy = y - cy;
            const int d2 = dx * dx + dy * dy;
            if (d2 > ro2 || d2 < ri2) continue;

            // atan2(dx, -dy) : 0 en haut, +pi/2 à droite -> sens horaire.
            float a = atan2f((float)dx, (float)-dy);
            if (a < 0.0f) a += 6.283185f;
            pixel(c, x, y, (a <= sweep) ? fg : bg);
        }
    }
}

void text(const Canvas& c, int x, int y, const char* s,
          uint16_t fg, uint16_t bg, uint8_t size) {
    if (!s || size == 0) return;
    const bool opaque = (bg != fg);

    for (; *s; s++, x += CHAR_W * size) {
        const uint8_t* glyph = FONT5X7 + (uint8_t)(*s) * 5;

        // 6e colonne = espacement : vide, mais peinte si le fond est opaque,
        // sinon les caractères se chevauchent sur un redessin.
        for (int col = 0; col < CHAR_W; col++) {
            uint8_t bits = (col < 5) ? glyph[col] : 0x00;
            for (int row = 0; row < CHAR_H; row++) {
                bool on = bits & (1 << row);
                if (!on && !opaque) continue;
                uint16_t color = on ? fg : bg;
                if (size == 1) pixel(c, x + col, y + row, color);
                else fill_rect(c, x + col * size, y + row * size, size, size, color);
            }
        }
    }
}

int text_w(const char* s, uint8_t size) {
    int n = 0;
    for (const char* p = s; p && *p; p++) n++;
    return n * CHAR_W * size;
}

